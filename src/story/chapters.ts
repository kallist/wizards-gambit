export function trialScore(s: GameState): number {
  if (s.result?.winner !== "white" || s.result.reason !== "checkmate") return 0;
  const captures: Record<string, number> = {
    p: 10,
    n: 32,
    b: 33,
    r: 50,
    q: 90,
  };
  const moves = s.history.filter(
    (h) => h.color === "white" && h.type === "move",
  );
  const scored = new Set<string>();
  return (
    1000 +
    Math.min(
      500,
      moves.reduce((sum, m, i) => {
        if (!m.captured) return sum;
        const id = m.capturedId ?? `legacy-${i}`;
        if (scored.has(id)) return sum;
        scored.add(id);
        return sum + (captures[m.captured] ?? 0);
      }, 0),
    ) +
    Math.max(0, 300 - moves.length * 10)
  );
}
