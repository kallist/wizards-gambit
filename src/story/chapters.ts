import { fromFEN } from "../domain/engine";
import type { GameState, SpellId } from "../domain/types";

export type Trigger =
  "start" | "move" | "capture" | "spell" | "check" | "win" | "loss" | "date";
export interface Dialogue {
  id: string;
  trigger: Trigger;
  malfoy: string;
  harry: string;
  frame: number;
}
export interface SceneLine {
  speaker: "马尔福" | "哈利" | "旁白";
  text: string;
}
export interface Chapter {
  id: number;
  title: string;
  subtitle: string;
  location: string;
  goal: string;
  fen: string;
  cards: SpellId[];
  opening: SceneLine[];
  closing: SceneLine[];
  dialogues: Dialogue[];
}
const m = (text: string): SceneLine => ({ speaker: "马尔福", text });
const h = (text: string): SceneLine => ({ speaker: "哈利", text });
const n = (text: string): SceneLine => ({ speaker: "旁白", text });
const dialogue = (
  chapter: number,
  groups: [Trigger, string, string][],
): Dialogue[] =>
  groups.map(([trigger, malfoy, harry], i) => ({
    id: `${chapter}-${i}`,
    trigger,
    malfoy,
    harry,
    frame:
      trigger === "spell"
        ? 4
        : trigger === "capture"
          ? 6
          : trigger === "check" || trigger === "loss"
            ? 5
            : trigger === "date" || trigger === "win"
              ? 7
              : 0,
  }));

