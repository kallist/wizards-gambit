export function chapterGame(index: number): GameState {
  const chapter = CHAPTERS[index],
    s = fromFEN(chapter.fen, "magic", 74100 + index);
  s.hands.white = chapter.cards.map((spell, i) => ({
    id: `chapter-${index}-${i}`,
    spell,
    readyPly: 0,
  }));
  return s;
}
export function chapterComplete(index: number, s: GameState): boolean {
  const moves = s.history.filter(
      (h) => h.color === "white" && h.type === "move",
    ),
    casts = s.history.filter((h) => h.color === "white" && h.type === "cast");
  const captured = moves.filter((h) => h.captured).length;
  if (index === 0) return moves.some((h) => h.captured && h.captured !== "p");
  if (index === 1) return casts.length > 0 && captured > 0;
  if (index === 2)
    return (
      moves.length >= 3 &&
      s.board.some((p) => p?.color === "white" && p.kind === "q")
    );
  if (index === 4) return casts.length > 0 && captured >= 2;
  return s.result?.winner === "white" && s.result.reason === "checkmate";
}
