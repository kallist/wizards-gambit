export interface DatePage {
  speaker: "旁白" | "马尔福" | "哈利";
  text: string;
  expression: Expression;
  choice?: { labels: [string, string]; index: 0 | 1 };
}
export interface DateReading {
  line: number;
  choices: [number | null, number | null];
}
export const initialReading = (): DateReading => ({
  line: 0,
  choices: [null, null],
});
const READING_KEY = "wizards-gambit-dates-v1";
export function readDate(
  id: OutfitId,
  storage = getPlayerStorage(),
): DateReading {
  try {
    const raw = storage.getItem(READING_KEY);
    if (!raw || raw.length > 12000) return initialReading();
    const x = JSON.parse(raw)[id];
    if (
      Number.isInteger(x?.line) &&
      x.line >= 0 &&
      x.line < 24 &&
      Array.isArray(x.choices) &&
      x.choices.length === 2 &&
      x.choices.every((c: unknown) => c === null || c === 0 || c === 1)
    ) {
      // A forged/incomplete save must not skip an unanswered branch.
      const line =
        x.line > 5 && x.choices[0] === null
          ? 5
          : x.line > 17 && x.choices[1] === null
            ? 17
            : x.line;
      return { line, choices: [...x.choices] as DateReading["choices"] };
    }
  } catch {
    /* Invalid/unavailable reading storage starts at the first page. */
  }
  return initialReading();
}
export function saveDate(
  id: OutfitId,
  reading: DateReading,
  storage = getPlayerStorage(),
) {
  try {
    const raw = storage.getItem(READING_KEY);
    const parsed = raw && raw.length < 12000 ? JSON.parse(raw) : {};
    const previous =
      parsed && typeof parsed === "object" && !Array.isArray(parsed)
        ? parsed
        : {};
    // Only preserve known outfit keys and validated records.
    const data: Partial<
      Record<OutfitId, DateReading & { updatedAt?: number }>
    > = {};
    for (const key of Object.keys(SETTINGS) as OutfitId[])
      if (previous[key])
        data[key] = {
          ...readDate(key, storage),
          ...(Number.isSafeInteger(previous[key].updatedAt) &&
          previous[key].updatedAt >= 0
            ? { updatedAt: previous[key].updatedAt }
            : {}),
        };
    data[id] = { ...reading, updatedAt: Date.now() };
    storage.setItem(READING_KEY, JSON.stringify(data));
    return true;
  } catch {
    return false;
  }
}
export function dateTitle(id: OutfitId) {
  return SETTINGS[id].title;
}
export function datePages(
  id: OutfitId,
  choices: DateReading["choices"],
): DatePage[] {
  const s = SETTINGS[id],
    pages: DatePage[] = [];
  const add = (
    speaker: DatePage["speaker"],
    text: string,
    expression: Expression = 0,
  ) => pages.push({ speaker, text, expression });
  const pair = (index: number, expression: Expression) => {
    add("马尔福", s.moments[index][0], expression);
    add("哈利", s.moments[index][1], expression);
  };
  add("旁白", `${s.place}。${s.detail} 她看了哈利一眼，像是还有一句话没说。`);
  pair(0, 0);
  add("旁白", "她停了一下。哈利等着，没替她把话说完。", 1);
  add("马尔福", s.moments[1][0], 1);
  pages.push({
    speaker: "哈利",
    text: "想怎么回应她？",
    expression: 1,
    choice: {
      index: 0,
      labels: [s.moments[1][1], "先不说话，伸出手，等她愿意靠近。"],
    },
  });
  add(
    "马尔福",
    choices[0] === 1 ? "……手给你。别一直伸着，怪傻的。" : s.reply[0],
    choices[0] === 1 ? 7 : 2,
  );
  add("哈利", choices[0] === 1 ? "那就握一会儿。" : s.reply[1], 2);
  add("旁白", `${s.detail} 哈利看见她嘴角动了动。这次他没有拆穿。`, 4);
  pair(2, 3);
  pair(3, 5);
  add("旁白", "她没再接话，只把衣袖上的褶痕捋平。过了一会儿，才又抬起头。", 6);
  pair(4, 6);
  add("马尔福", s.moments[5][0], 1);
  pages.push({
    speaker: "哈利",
    text: "接下来呢？",
    expression: 1,
    choice: {
      index: 1,
      labels: [s.moments[5][1], `邀请她：${s.invitation}。`],
    },
  });
  add(
    "马尔福",
    choices[1] === 1 ? s.acceptance[0] : "记住了。下次别说是我逼你答应的。",
    2,
  );
  add("哈利", choices[1] === 1 ? s.acceptance[1] : `我会${s.promise}。`, 7);
  add("旁白", "她终于笑出了声。哈利刚想说什么，她便捏了捏他的手。", 7);
  pair(6, 7);
  add("旁白", `${s.title} · 终。她先往前走了两步，又回过头来等他。`, 7);
  return pages;
}
