export function Icon({
  name,
  size = 20,
  className = "",
}: {
  name: string;
  size?: number;
  className?: string;
}) {
  const C = icons[name as keyof typeof icons] ?? Sparkles;
  return (
    <C
      size={size}
      strokeWidth={1.55}
      aria-hidden="true"
      className={className}
    />
  );
}
